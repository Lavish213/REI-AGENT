const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {PGlite}=require('@electric-sql/pglite');
const tenant='00000000-0000-0000-0000-000000000001',other='00000000-0000-0000-0000-000000000002';
const lead='00000000-0000-0000-0000-000000000010',lead2='00000000-0000-0000-0000-000000000011',foreign='00000000-0000-0000-0000-000000000012';
const migration=fs.readFileSync(path.join(__dirname,'../supabase/migrations/20261113_campaign_tenant_and_call_lifecycle.sql'),'utf8');
const legacy=`create role anon;create role authenticated;create role service_role;
 create table tenants(id uuid primary key,slug text,legal_name text);
 insert into tenants values ('${tenant}','a','A'),('${other}','b','B');
 create table leads(id uuid primary key,tenant_id uuid not null);
 insert into leads values ('${lead}','${tenant}'),('${lead2}','${tenant}'),('${foreign}','${other}');
 create table campaigns(id text primary key,state text not null default 'paused' check (state in ('paused','running')),created_at timestamptz not null default now());
 insert into campaigns(id,state) values ('default','running');
 create table calls(id uuid primary key default gen_random_uuid(),lead_id uuid,signalwire_call_id text,transcript text,call_disposition text,created_at timestamptz default now());`;
(async()=>{
 const db=new PGlite();
 try {
  await db.exec(legacy);
  await assert.rejects(db.query("select state from campaigns where id='default' and tenant_id=$1",[tenant]),/tenant_id/);
  await db.exec(migration);await db.exec(migration);
  let rows=(await db.query("select state,tenant_id from campaigns where id='default' and tenant_id=$1",[tenant])).rows;
  assert.deepEqual(rows,[{state:'running',tenant_id:tenant}]);
  await db.query("insert into campaigns(tenant_id,id,state) values ($1,'default','paused')",[other]);
  assert.equal((await db.query("select state from campaigns where id='default' and tenant_id=$1",[other])).rows[0].state,'paused');
  assert.equal((await db.query("select state from campaigns where id='default' and tenant_id=$1",[tenant])).rows[0].state,'running');
  await assert.rejects(db.query("insert into campaigns(tenant_id,id) values ($1,'default')",[tenant]),/duplicate key/);
  await assert.rejects(db.query("insert into campaigns(tenant_id,id) values ('00000000-0000-0000-0000-0000000000ff','x')"),/foreign key/);
  assert.equal((await db.query("select relrowsecurity from pg_class where relname='campaigns'")).rows[0].relrowsecurity,true);
  const life=(sid,status,{l=lead,dir='outbound',dur=0,t=tenant}={})=>db.query('select record_call_lifecycle($1,$2,$3,$4,$5,$6) as id',[t,l,sid,dir,status,dur]).then(r=>r.rows[0].id);
  const row=sid=>db.query('select * from calls where signalwire_call_id=$1',[sid]).then(r=>r.rows);
  const id=await life('CA1','initiated');
  assert.equal(await life('CA1','ringing'),id);
  assert.equal(await life('CA1','completed',{dur:8}),id);
  assert.equal(await life('CA1','in-progress',{dur:3}),id);
  assert.equal(await life('CA1','completed',{dur:8}),id);
  let r=await row('CA1');
  assert.equal(r.length,1);
  assert.equal(r[0].provider_status,'completed');assert.equal(r[0].duration_seconds,8);assert.equal(r[0].direction,'outbound');assert.equal(r[0].lead_id,lead);assert.ok(r[0].ended_at);
  const ended=r[0].ended_at;
  await life('CA1','failed');
  r=await row('CA1');assert.equal(r[0].provider_status,'completed');assert.equal(r[0].ended_at.getTime(),ended.getTime());
  await life('CA2','no-answer');await life('CA2','initiated');
  r=await row('CA2');assert.equal(r[0].provider_status,'no-answer');assert.equal(r[0].provider_status_rank,40);
  await Promise.all(Array.from({length:200},(_,i)=>life('CA3',['initiated','ringing','in-progress','completed'][i%4],{dur:i%30})));
  r=await row('CA3');assert.equal(r.length,1);assert.equal(r[0].provider_status,'completed');assert.equal(r[0].duration_seconds,29);
  await assert.rejects(life('CA1','completed',{l:lead2}),/lead mismatch/);
  await assert.rejects(life('CA1','completed',{dir:'inbound'}),/direction mismatch/);
  await assert.rejects(life('CA4','completed',{l:foreign}),/Lead not found for tenant/);
  await assert.rejects(life('CA5','bogus'),/Invalid provider call status/);
  await assert.rejects(life("CA'; drop",'completed'),/Invalid provider call ID/);
  await assert.rejects(life('','completed'),/Invalid provider call ID/);
  await assert.rejects(db.query("select record_call_lifecycle($1,$2,'CA6','outbound','initiated',0)",[tenant,'not-a-uuid']),/invalid input syntax for type uuid/);
  assert.equal((await row('CA4')).length+(await row('CA5')).length,0);
  const inboundId=await life('CA7','in-progress',{l:null,dir:'inbound'});
  assert.equal(await life('CA7','completed',{l:lead,dir:null,dur:40}),inboundId);
  r=await row('CA7');assert.equal(r[0].lead_id,lead);assert.equal(r[0].direction,'inbound');
  const rec=(sid,url,rsid)=>db.query('select record_call_recording($1,$2,$3,$4,$5,$6) as id',[tenant,lead,sid,url,rsid,61]).then(x=>x.rows[0].id);
  const recId=await rec('CA8','https://example.invalid/r1','RE1');
  assert.equal(await life('CA8','completed',{dur:62}),recId);
  assert.equal(await rec('CA8','https://example.invalid/r2','RE2'),recId);
  r=await row('CA8');assert.equal(r[0].recording_sid,'RE1');assert.equal(r[0].recording_url,'https://example.invalid/r1');assert.equal(r[0].provider_status,'completed');assert.equal(r[0].recording_duration_seconds,61);
  await assert.rejects(rec('CA9','','RE9'),/Recording URL is required/);
  assert.equal(await life('CA1','completed',{t:other,l:null}),(await row('CA1')).find(x=>x.tenant_id===other).id);
  assert.equal((await row('CA1')).length,2);
  const dup=new PGlite();
  try {
   await dup.exec(legacy);
   await dup.exec("insert into calls(signalwire_call_id) values ('CAX'),('CAX')");
   await assert.rejects(dup.exec(migration),/duplicate provider call IDs/);
  } finally { await dup.close(); }
  console.log('call lifecycle database checks passed');
 } finally { await db.close(); }
})().catch(error=>{console.error(error);process.exit(1);});
